/** Insere o emoji na posição do cursor e devolve o texto e o novo cursor. */
export const inserirEmoji = (valor, inicio, fim, emoji) => {
  const bruto = String(valor ?? '');
  const de = Math.max(0, Math.min(Number(inicio) || 0, bruto.length));
  const ate = Math.max(de, Math.min(Number(fim) || de, bruto.length));
  const texto = `${bruto.slice(0, de)}${emoji}${bruto.slice(ate)}`;
  const cursor = de + emoji.length;
  return { texto, cursor };
};
